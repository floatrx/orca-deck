#!/bin/sh
# Prepares the transport probe: writes Probe/Secrets.generated.swift (token + URLs, gitignored)
# and generates OrcaDeckProbe.xcodeproj with XcodeGen.
#
#   probe/configure.sh [tunnel-url]
#
# tunnel-url: the https://….trycloudflare.com address printed by
#   cloudflared tunnel --url http://localhost:7353
# Quick tunnels get a new address per run: start the tunnel first, then run this script, then build.
set -eu

DIR=$(cd "$(dirname "$0")" && pwd)
CONFIG="$HOME/.config/orca-deck/bridge.json"
TUNNEL="${1:-}"

[ -f "$CONFIG" ] || { echo "no $CONFIG — load the bridge once first" >&2; exit 1; }
TOKEN=$(jq -r .token "$CONFIG")
LAN_IP=$(ipconfig getifaddr en0 || true)
[ -n "$LAN_IP" ] || { echo "en0 has no IP address" >&2; exit 1; }

cat > "$DIR/Probe/Secrets.generated.swift" <<EOF
// Generated by probe/configure.sh on $(date '+%Y-%m-%d %H:%M'). Gitignored — never commit.
enum Secrets {
    static let token = "$TOKEN"
    static let lanBase = "http://$LAN_IP:7353"
    static let tunnelBase = "${TUNNEL%/}"
}
EOF
echo "wrote Probe/Secrets.generated.swift (LAN $LAN_IP, tunnel ${TUNNEL:-none})"

# The team ID: $DEVELOPMENT_TEAM if set, else the first team Xcode lists under Settings → Apple
# Accounts (IDEProvisioningTeamByIdentifier), else the OU of an "Apple Development" certificate.
TEAM="${DEVELOPMENT_TEAM:-}"
[ -n "$TEAM" ] || TEAM=$(defaults read com.apple.dt.Xcode IDEProvisioningTeamByIdentifier 2>/dev/null \
  | sed -n 's/.*teamID = \([A-Z0-9]*\);.*/\1/p' | head -1)
[ -n "$TEAM" ] || TEAM=$(security find-certificate -a -c "Apple Development" -p 2>/dev/null \
  | openssl x509 -noout -subject 2>/dev/null | sed -n 's/.*OU *= *\([A-Z0-9]*\).*/\1/p' | head -1)
[ -n "$TEAM" ] || echo "no team found — sign in under Xcode → Settings → Apple Accounts, or pick it in Signing & Capabilities"

cd "$DIR" && DEVELOPMENT_TEAM="$TEAM" xcodegen generate --quiet
echo "generated probe/OrcaDeckProbe.xcodeproj (team ${TEAM:-unset}) — open it, pick the watch, Run"
