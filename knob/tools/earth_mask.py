"""Rasterizes Natural Earth land polygons (public domain) into knob/deck/earth_mask.h: a W x H equirectangular bit
mask for the hub's globe (row 0 = 90°N, column 0 = 180°W, bit 7 of a byte = the westmost cell).

Get the source: https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson
Run: python3 knob/tools/earth_mask.py ne_110m_land.geojson knob/deck/earth_mask.h
"""
import json
import sys

W, H = 180, 90


def rings_of(path):
    rings = []
    for feature in json.load(open(path))["features"]:
        geometry = feature["geometry"]
        polygons = [geometry["coordinates"]] if geometry["type"] == "Polygon" else geometry["coordinates"]
        for polygon in polygons:
            rings += polygon
    return rings


def inside(rings, x, y):
    hit = False  # even-odd rule: holes (lakes) flip it back
    for ring in rings:
        for i in range(len(ring)):
            x1, y1 = ring[i]
            x2, y2 = ring[i - 1]
            if (y1 > y) != (y2 > y) and x < (x2 - x1) * (y - y1) / (y2 - y1) + x1:
                hit = not hit
    return hit


def main():
    rings = rings_of(sys.argv[1])
    stride = (W + 7) // 8
    out = []
    for j in range(H):
        lat = 90 - (j + 0.5) * 180 / H
        row = [0] * stride
        for i in range(W):
            if inside(rings, -180 + (i + 0.5) * 360 / W, lat):
                row[i // 8] |= 0x80 >> (i % 8)
        out.append(", ".join(f"0x{b:02X}" for b in row))
    with open(sys.argv[2], "w") as f:
        f.write("// Generated by knob/tools/earth_mask.py from Natural Earth 1:110m land (public domain).\n")
        f.write("#pragma once\n#include <stdint.h>\n\n")
        f.write(f"#define EARTH_W {W}\n#define EARTH_H {H}\n#define EARTH_STRIDE {stride}\n\n")
        f.write("static const uint8_t EARTH_MASK[EARTH_H][EARTH_STRIDE] = {\n")
        f.write("".join(f"  {{{line}}},\n" for line in out))
        f.write("};\n")


if __name__ == "__main__":
    main()
